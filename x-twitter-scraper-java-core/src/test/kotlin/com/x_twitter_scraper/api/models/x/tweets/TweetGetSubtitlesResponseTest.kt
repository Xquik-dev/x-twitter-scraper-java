package com.x_twitter_scraper.api.models.x.tweets

import com.fasterxml.jackson.module.kotlin.jacksonTypeRef
import com.x_twitter_scraper.api.core.jsonMapper
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test

internal class TweetGetSubtitlesResponseTest {

    @Test
    fun create() {
        val tweetGetSubtitlesResponse =
            TweetGetSubtitlesResponse.builder()
                .subtitles(
                    TweetGetSubtitlesResponse.Subtitles.builder()
                        .addTrack(
                            TweetGetSubtitlesResponse.Subtitles.Track.builder()
                                .autoGenerated(false)
                                .addCue(
                                    TweetGetSubtitlesResponse.Subtitles.Track.Cue.builder()
                                        .endMs(3370L)
                                        .startMs(0L)
                                        .text("This asteroid\n2024 YR4 might get interesting.")
                                        .build()
                                )
                                .text("This asteroid 2024 YR4 might get interesting.")
                                .truncated(false)
                                .url(
                                    "https://video.twimg.com/subtitles/amplify_video/2104593621043314689/0/-FdxBBY2iGcoP5wb.vtt"
                                )
                                .language("en")
                                .mediaKey("13_2104593621043314689")
                                .name("Planetary Defenders_Caption.en_US.srt")
                                .build()
                        )
                        .tweetId("2104593672624886205")
                        .build()
                )
                .build()

        assertThat(tweetGetSubtitlesResponse.subtitles())
            .isEqualTo(
                TweetGetSubtitlesResponse.Subtitles.builder()
                    .addTrack(
                        TweetGetSubtitlesResponse.Subtitles.Track.builder()
                            .autoGenerated(false)
                            .addCue(
                                TweetGetSubtitlesResponse.Subtitles.Track.Cue.builder()
                                    .endMs(3370L)
                                    .startMs(0L)
                                    .text("This asteroid\n2024 YR4 might get interesting.")
                                    .build()
                            )
                            .text("This asteroid 2024 YR4 might get interesting.")
                            .truncated(false)
                            .url(
                                "https://video.twimg.com/subtitles/amplify_video/2104593621043314689/0/-FdxBBY2iGcoP5wb.vtt"
                            )
                            .language("en")
                            .mediaKey("13_2104593621043314689")
                            .name("Planetary Defenders_Caption.en_US.srt")
                            .build()
                    )
                    .tweetId("2104593672624886205")
                    .build()
            )
    }

    @Test
    fun roundtrip() {
        val jsonMapper = jsonMapper()
        val tweetGetSubtitlesResponse =
            TweetGetSubtitlesResponse.builder()
                .subtitles(
                    TweetGetSubtitlesResponse.Subtitles.builder()
                        .addTrack(
                            TweetGetSubtitlesResponse.Subtitles.Track.builder()
                                .autoGenerated(false)
                                .addCue(
                                    TweetGetSubtitlesResponse.Subtitles.Track.Cue.builder()
                                        .endMs(3370L)
                                        .startMs(0L)
                                        .text("This asteroid\n2024 YR4 might get interesting.")
                                        .build()
                                )
                                .text("This asteroid 2024 YR4 might get interesting.")
                                .truncated(false)
                                .url(
                                    "https://video.twimg.com/subtitles/amplify_video/2104593621043314689/0/-FdxBBY2iGcoP5wb.vtt"
                                )
                                .language("en")
                                .mediaKey("13_2104593621043314689")
                                .name("Planetary Defenders_Caption.en_US.srt")
                                .build()
                        )
                        .tweetId("2104593672624886205")
                        .build()
                )
                .build()

        val roundtrippedTweetGetSubtitlesResponse =
            jsonMapper.readValue(
                jsonMapper.writeValueAsString(tweetGetSubtitlesResponse),
                jacksonTypeRef<TweetGetSubtitlesResponse>(),
            )

        assertThat(roundtrippedTweetGetSubtitlesResponse).isEqualTo(tweetGetSubtitlesResponse)
    }
}
